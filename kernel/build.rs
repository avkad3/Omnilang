//! Build script.
//!
//! 1. Links with `linker.ld`.
//! 2. Compiles `messages.toml` into string constants (for the serial console).
//! 3. Renders the same messages into bitmaps for the framebuffer panic screen.
//!
//! Indic scripts need *shaping*: Devanagari forms conjuncts and reorders
//! vowel signs, Tamil uses ligatures and two-part vowels. A kernel panicking
//! before anything is loaded cannot run a shaping engine, so the shaping is
//! done here, at build time, with rustybuzz (a Rust port of HarfBuzz), and
//! the kernel only copies finished bitmaps. Numbers and addresses are the
//! only dynamic text; they use per-glyph atlases that need no shaping.

use std::collections::BTreeMap;
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use ab_glyph::{Font as _, FontRef, GlyphId, PxScale};

const LANGS: [&str; 3] = ["en", "hi", "ta"];

fn main() {
    let dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());

    println!("cargo:rustc-link-arg=-T{}", dir.join("linker.ld").display());
    println!("cargo:rerun-if-changed=linker.ld");
    println!("cargo:rerun-if-changed=messages.toml");
    println!("cargo:rerun-if-changed=fonts");

    let src = fs::read_to_string(dir.join("messages.toml")).expect("read messages.toml");
    let messages: BTreeMap<String, BTreeMap<String, String>> =
        toml::from_str(&src).expect("messages.toml is valid TOML");
    for (key, tr) in &messages {
        for l in LANGS {
            assert!(tr.contains_key(l), "messages.toml: [{key}] is missing '{l}'");
        }
    }

    fs::write(out.join("messages.rs"), strings(&messages)).unwrap();

    let fonts = Fonts::load(&dir.join("fonts"));
    let mut blob = Blob::default();
    let code = bitmaps(&messages, &fonts, &mut blob);
    fs::write(out.join("glyphs.rs"), code).unwrap();
    fs::write(out.join("glyphs.bin"), &blob.bytes).unwrap();
}

// ---------------------------------------------------------------- strings

fn strings(messages: &BTreeMap<String, BTreeMap<String, String>>) -> String {
    let mut code = String::from("// Generated by build.rs from messages.toml.\n\n");
    let _ = writeln!(code, "pub const LANGS: [&str; {}] = {LANGS:?};\n", LANGS.len());
    for (key, tr) in messages {
        let values: Vec<&String> = LANGS.iter().map(|l| &tr[*l]).collect();
        let _ = writeln!(
            code,
            "pub const {}: [&str; {}] = {values:?};",
            key.to_uppercase(),
            LANGS.len()
        );
    }
    code
}

// ---------------------------------------------------------------- fonts

struct FontFile {
    data: Vec<u8>,
}

impl FontFile {
    fn load(path: &Path) -> FontFile {
        FontFile {
            data: fs::read(path).unwrap_or_else(|e| panic!("{}: {e}", path.display())),
        }
    }
    fn shaper(&self) -> rustybuzz::Face<'_> {
        rustybuzz::Face::from_slice(&self.data, 0).expect("valid font")
    }
    fn raster(&self) -> FontRef<'_> {
        FontRef::try_from_slice(&self.data).expect("valid font")
    }
}

struct Fonts {
    latin: [FontFile; 2], // regular, bold
    devanagari: [FontFile; 2],
    tamil: [FontFile; 2],
    mono: FontFile,
}

impl Fonts {
    fn load(dir: &Path) -> Fonts {
        let f = |name: &str| FontFile::load(&dir.join(name));
        Fonts {
            latin: [f("NotoSans-Regular.ttf"), f("NotoSans-Bold.ttf")],
            devanagari: [
                f("NotoSansDevanagari-Regular.ttf"),
                f("NotoSansDevanagari-Bold.ttf"),
            ],
            tamil: [f("NotoSansTamil-Regular.ttf"), f("NotoSansTamil-Bold.ttf")],
            mono: f("NotoSansMono-Regular.ttf"),
        }
    }

    /// Primary font for a language, plus the Latin fallback for characters
    /// it lacks (punctuation, Latin letters).
    fn for_lang(&self, lang: &str, bold: bool) -> (&FontFile, &FontFile) {
        let w = bold as usize;
        let primary = match lang {
            "hi" => &self.devanagari[w],
            "ta" => &self.tamil[w],
            _ => &self.latin[w],
        };
        (primary, &self.latin[w])
    }
}

// ---------------------------------------------------------------- rendering

struct Rendered {
    width: usize,
    height: usize,
    baseline: usize,
    advance: usize,
    coverage: Vec<u8>,
}

/// Font units → pixels for an em size of `px`.
fn ppu(face: &rustybuzz::Face, px: f32) -> f32 {
    px / face.units_per_em() as f32
}

/// ab_glyph's PxScale is relative to (ascent - descent), not the em.
fn px_scale(font: &FontRef, px: f32) -> PxScale {
    let upem = font.units_per_em().expect("scalable font");
    PxScale::from(px * font.height_unscaled() / upem)
}

/// Shapes and rasterizes `text` at `px`, splitting it into runs so that
/// characters missing from `primary` are drawn with `fallback`.
fn render(text: &str, px: f32, primary: &FontFile, fallback: &FontFile) -> Rendered {
    let fonts = [primary, fallback];
    let shapers = [primary.shaper(), fallback.shaper()];
    let rasters = [primary.raster(), fallback.raster()];

    // Line metrics cover both fonts so mixed runs share one baseline.
    let ascent = (0..2)
        .map(|i| shapers[i].ascender() as f32 * ppu(&shapers[i], px))
        .fold(0.0, f32::max);
    let descent = (0..2)
        .map(|i| -(shapers[i].descender() as f32) * ppu(&shapers[i], px))
        .fold(0.0, f32::max);
    let (ascent, descent) = (ascent.ceil() as usize, descent.ceil() as usize);

    // Split into runs by font; whitespace stays with the current run.
    let mut runs: Vec<(usize, String)> = Vec::new();
    for c in text.chars() {
        let font = if c.is_whitespace() {
            runs.last().map_or(0, |r| r.0)
        } else if shapers[0].glyph_index(c).is_some() {
            0
        } else {
            1
        };
        match runs.last_mut() {
            Some((f, s)) if *f == font => s.push(c),
            _ => runs.push((font, c.to_string())),
        }
    }

    // Shape every run, collecting positioned glyphs.
    let mut placed: Vec<(usize, u16, f32, f32)> = Vec::new(); // (font, glyph, x, y-offset)
    let mut pen = 0.0f32;
    for (font, run) in &runs {
        let face = &shapers[*font];
        let scale = ppu(face, px);
        let mut buf = rustybuzz::UnicodeBuffer::new();
        buf.push_str(run);
        buf.guess_segment_properties();
        let shaped = rustybuzz::shape(face, &[], buf);
        for (info, pos) in shaped.glyph_infos().iter().zip(shaped.glyph_positions()) {
            placed.push((
                *font,
                info.glyph_id as u16,
                pen + pos.x_offset as f32 * scale,
                pos.y_offset as f32 * scale,
            ));
            pen += pos.x_advance as f32 * scale;
        }
    }
    let _ = fonts;

    let pad = 2; // room for glyphs that overhang their advance
    let width = pen.ceil() as usize + 2 * pad;
    let height = ascent + descent;
    let mut coverage = vec![0u8; width * height];
    for (font, gid, x, yoff) in placed {
        let raster = &rasters[font];
        let glyph = GlyphId(gid).with_scale_and_position(
            px_scale(raster, px),
            ab_glyph::point(x + pad as f32, ascent as f32 - yoff),
        );
        if let Some(outline) = raster.outline_glyph(glyph) {
            let b = outline.px_bounds();
            outline.draw(|gx, gy, c| {
                let x = b.min.x as i32 + gx as i32;
                let y = b.min.y as i32 + gy as i32;
                if x >= 0 && y >= 0 && (x as usize) < width && (y as usize) < height {
                    let i = y as usize * width + x as usize;
                    coverage[i] = coverage[i].max((c.clamp(0.0, 1.0) * 255.0).round() as u8);
                }
            });
        }
    }
    Rendered {
        width,
        height,
        baseline: ascent,
        advance: pen.round() as usize,
        coverage,
    }
}

// ---------------------------------------------------------------- output

/// All bitmaps, run-length encoded: `0x00 n` is a run of `n` transparent
/// pixels (1..=255); any other byte is one pixel's coverage.
#[derive(Default)]
struct Blob {
    bytes: Vec<u8>,
}

impl Blob {
    fn add(&mut self, r: &Rendered) -> String {
        let offset = self.bytes.len();
        let mut zeros = 0usize;
        for &c in &r.coverage {
            if c == 0 {
                zeros += 1;
                if zeros == 255 {
                    self.bytes.extend([0, 255]);
                    zeros = 0;
                }
            } else {
                if zeros > 0 {
                    self.bytes.extend([0, zeros as u8]);
                    zeros = 0;
                }
                self.bytes.push(c);
            }
        }
        if zeros > 0 {
            self.bytes.extend([0, zeros as u8]);
        }
        format!(
            "Bitmap::new({}, {}, {}, {}, {offset}, {})",
            r.width,
            r.height,
            r.baseline,
            r.advance,
            self.bytes.len() - offset
        )
    }
}

/// Which messages become bitmaps, and how they look.
fn style(key: &str) -> Option<(f32, bool)> {
    match key {
        "title" => Some((40.0, true)),
        "boot" => Some((28.0, true)),
        k if k.starts_with("cause_") && k != "cause_label" => Some((24.0, true)),
        "subtitle" | "footer" | "cause_label" | "pc_label" | "addr_label" | "ticks_label"
        | "detail_label" => Some((20.0, false)),
        _ => None, // digits are rendered as an atlas instead
    }
}

const TEXT_PX: f32 = 20.0;
const MONO_PX: f32 = 18.0;

fn bitmaps(messages: &BTreeMap<String, BTreeMap<String, String>>, fonts: &Fonts, blob: &mut Blob) -> String {
    let mut code = String::from("// Generated by build.rs: pre-shaped text bitmaps.\n\n");
    let mut total = 0usize;

    for (key, tr) in messages {
        let Some((px, bold)) = style(key) else { continue };
        let entries: Vec<String> = LANGS
            .iter()
            .map(|l| {
                let (primary, fallback) = fonts.for_lang(l, bold);
                let r = render(&tr[*l], px, primary, fallback);
                total += r.width * r.height;
                blob.add(&r)
            })
            .collect();
        let _ = writeln!(
            code,
            "pub const {}: [Bitmap; 3] = [{}];",
            key.to_uppercase(),
            entries.join(", ")
        );
    }

    // Native digits for each language (no shaping needed for single digits).
    let digit_sets: Vec<String> = LANGS
        .iter()
        .map(|l| {
            let (primary, fallback) = fonts.for_lang(l, false);
            let glyphs: Vec<String> = messages["digits"][*l]
                .chars()
                .map(|d| blob.add(&render(&d.to_string(), TEXT_PX, primary, fallback)))
                .collect();
            format!("[{}]", glyphs.join(", "))
        })
        .collect();
    let _ = writeln!(
        code,
        "pub const DIGITS: [[Bitmap; 10]; 3] = [{}];",
        digit_sets.join(", ")
    );

    // Printable ASCII in a monospace font, for addresses and panic details.
    let mono: Vec<String> = (0x20u8..0x7F)
        .map(|c| {
            blob.add(&render(
                &(c as char).to_string(),
                MONO_PX,
                &fonts.mono,
                &fonts.mono,
            ))
        })
        .collect();
    let _ = writeln!(code, "pub const MONO: [Bitmap; 95] = [{}];", mono.join(", "));

    println!(
        "cargo:warning=glyphs: {} KiB of shaped text compressed to {} KiB",
        total / 1024,
        blob.bytes.len() / 1024
    );
    code
}
